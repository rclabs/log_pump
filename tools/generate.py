#!/usr/bin/env python3
"""Generate plain C++17 payload types/encoders and a canonical JSON dictionary."""
import argparse
import json
from pathlib import Path
import sys

from schema import TYPES, digest, load

def generate(schema):
    lines = ["// Generated by log_pump; do not edit.", "#pragma once", '#include "log_pump/wire.hpp"',
             "#include <array>", "#include <cstddef>", "#include <cstdint>", "", f'namespace {schema["namespace"]} {{']
    sizes = []
    for record in schema["records"]:
        size = sum(TYPES[f["type"]][2] * f["count"] for f in record["fields"])
        sizes.append(size)
        lines += [f'struct {record["name"]} {{', f'    static constexpr std::uint16_t type_id = {record["id"]};',
                  f"    static constexpr std::size_t encoded_size = {size};"]
        for field in record["fields"]:
            cpp = TYPES[field["type"]][0]
            if field["count"] > 1:
                cpp = f'std::array<{cpp}, {field["count"]}>'
            lines.append(f'    {cpp} {field["name"]}{{}};')
        lines.append("    void encode(std::uint8_t* out) const {")
        offset = 0
        for field in record["fields"]:
            _, _, width = TYPES[field["type"]]
            name, count, typ = field["name"], field["count"], field["type"]
            if count > 1:
                lines.append(f"        for (std::size_t i = 0; i < {count}; ++i) {{")
                value, dest, indent = f"{name}[i]", f"out + {offset} + i * {width}", "            "
            else:
                value, dest, indent = name, f"out + {offset}", "        "
            if typ.startswith("float"):
                call = f'log_pump::putFloat{width * 8}({dest}, {value});'
            else:
                call = f'log_pump::putUnsigned({dest}, static_cast<std::uint64_t>({value}), {width});'
            lines.append(indent + call)
            if count > 1:
                lines.append("        }")
            offset += width * count
        lines += ["    }", "};", ""]
    hash_bytes = ", ".join(f"0x{byte:02x}" for byte in bytes.fromhex(digest(schema)))
    lines += [f"inline constexpr log_pump::SchemaHash schema_hash{{{{{hash_bytes}}}}};",
              f"inline constexpr std::size_t max_payload_size = {max(sizes)};", "}", ""]
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema")
    parser.add_argument("--output-dir", required=True)
    args = parser.parse_args()
    try:
        schema = load(args.schema)
        header = generate(schema)
        destination = Path(args.output_dir)
        destination.mkdir(parents=True, exist_ok=True)
        (destination / "observations.hpp").write_text(header)
        (destination / "schema.json").write_text(json.dumps(schema, indent=2, sort_keys=True) + "\n")
    except (ValueError, TypeError, OSError) as exc:
        parser.exit(2, f"generation failed: {exc}\n")

if __name__ == "__main__":
    main()
